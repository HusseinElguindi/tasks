import XCTest
@testable import TasksCore

final class FractionalIndexTests: XCTestCase {
    struct Vectors: Decodable {
        var between: [[String?]]
        var nBetween: [NBetween]
        var errors: [[String?]]

        struct NBetween: Decodable {
            var a: String?, b: String?, n: Int, keys: [String]
            init(from decoder: Decoder) throws {
                var c = try decoder.unkeyedContainer()
                a = try c.decode(String?.self)
                b = try c.decode(String?.self)
                n = try c.decode(Int.self)
                keys = try c.decode([String].self)
            }
        }
    }

    /// Vectors generated by the `fractional-indexing` npm package (v3.2.0; v4.0.0 agrees on all of them).
    func testMatchesReferenceImplementation() throws {
        let url = try XCTUnwrap(Bundle.module.url(forResource: "Resources/fractional-index-vectors", withExtension: "json"))
        let v = try JSONDecoder().decode(Vectors.self, from: Data(contentsOf: url))
        XCTAssertGreaterThan(v.between.count, 2000)
        for row in v.between {
            XCTAssertEqual(try FractionalIndex.keyBetween(row[0], row[1]), row[2], "keyBetween(\(row[0] ?? "nil"), \(row[1] ?? "nil"))")
        }
        for row in v.nBetween {
            XCTAssertEqual(try FractionalIndex.keysBetween(row.a, row.b, count: row.n), row.keys)
        }
        for row in v.errors {
            XCTAssertThrowsError(try FractionalIndex.keyBetween(row[0], row[1]), "\(row)")
        }
    }

    func testBasics() throws {
        XCTAssertEqual(try FractionalIndex.keyBetween(nil, nil), "a0")
        XCTAssertEqual(try FractionalIndex.keyBetween("a0", nil), "a1")
        XCTAssertEqual(try FractionalIndex.keyBetween(nil, "a0"), "Zz")
        XCTAssertEqual(try FractionalIndex.keyBetween("a0", "a1"), "a0V")
        // Stricter than the JS original: the charset is checked too.
        XCTAssertThrowsError(try FractionalIndex.keyBetween("a0 ", nil))
        XCTAssertThrowsError(try FractionalIndex.keyBetween(nil, "a1-"))
        XCTAssertFalse(FractionalIndex.isValidKey("a 0"))
        XCTAssertTrue(FractionalIndex.isValidKey("a0V"))
    }

    /// Appending keeps keys short: 2–4 characters for thousands of items (spec §3).
    func testAppendGrowthIsLogarithmic() throws {
        var k: String? = nil
        for _ in 0..<5000 { k = try FractionalIndex.keyBetween(k, nil) }
        XCTAssertLessThanOrEqual(k!.count, 4)
    }

    /// Inserting at the same spot adds about one character per ~6 inserts.
    func testSameSpotGrowth() throws {
        let lo = "a0"
        var hi = "a1"
        for _ in 0..<60 { hi = try FractionalIndex.keyBetween(lo, hi) }
        XCTAssertLessThanOrEqual(hi.count, 2 + 60 / 5)
        XCTAssertGreaterThan(hi.count, 2 + 60 / 8)
    }
}

final class OrderingTests: XCTestCase {
    func items(_ pairs: [(String, String)]) -> [OrderedItem] { pairs.map { OrderedItem(id: $0.0, order: $0.1) } }

    func apply(_ placed: [OrderedItem], to list: [OrderedItem]) -> [String] {
        var byID = Dictionary(uniqueKeysWithValues: list.map { ($0.id, $0.order) })
        for p in placed { byID[p.id] = p.order }
        return byID.sorted { orderPrecedes($0.value, $0.key, $1.value, $1.key) }.map(\.key)
    }

    func testAppendToEmptyAndEnd() {
        XCTAssertEqual(Ordering.append(["x"], after: []), [OrderedItem(id: "x", order: "a0")])
        let list = items([("a", "a0"), ("b", "a1")])
        XCTAssertEqual(Ordering.append(["x"], after: list), [OrderedItem(id: "x", order: "a2")])
    }

    func testPlaceBetween() {
        let list = items([("a", "a0"), ("b", "a1"), ("c", "a2")])
        let placed = Ordering.place(["c"], at: .after("a"), in: list)
        XCTAssertEqual(placed.count, 1)
        XCTAssertEqual(apply(placed, to: list), ["a", "c", "b"])
        XCTAssertEqual(apply(Ordering.place(["a"], at: .bottom, in: list), to: list), ["b", "c", "a"])
        XCTAssertEqual(apply(Ordering.place(["c"], at: .top, in: list), to: list), ["c", "a", "b"])
        XCTAssertEqual(apply(Ordering.place(["a"], at: .before("c"), in: list), to: list), ["b", "a", "c"])
    }

    /// Drag k selected tasks: k keys from keysBetween(prev, next, k), one op each.
    func testMultiDrag() {
        let list = items([("a", "a0"), ("b", "a1"), ("c", "a2"), ("d", "a3")])
        let placed = Ordering.place(["d", "a"], at: .after("b"), in: list)
        XCTAssertEqual(placed.map(\.id), ["d", "a"])
        XCTAssertEqual(apply(placed, to: list), ["b", "d", "a", "c"])
    }

    /// Both Macs insert at the same spot: identical keys, and the id tie-break gives both the same order.
    func testTiesBreakByID() {
        let sorted = items([("y", "a1"), ("x", "a1"), ("w", "a0")])
            .sorted { orderPrecedes($0.order, $0.id, $1.order, $1.id) }
        XCTAssertEqual(sorted.map(\.id), ["w", "x", "y"])
    }

    /// Inserting between two equal keys first re-keys the tied run (spec §3).
    func testInsertBetweenTiedKeysRekeysRun() {
        let list = items([("a", "a0"), ("b", "a1"), ("c", "a1"), ("d", "a1"), ("e", "a2")])
        let placed = Ordering.place(["x"], at: .after("b"), in: list)
        // c and d get distinct keys above a1 (b keeps a1), then x lands between b and c.
        XCTAssertEqual(Set(placed.map(\.id)), ["c", "d", "x"])
        XCTAssertEqual(apply(placed, to: list), ["a", "b", "x", "c", "d", "e"])
        let keys = apply(placed, to: list).map { id in placed.first { $0.id == id }?.order ?? list.first { $0.id == id }!.order }
        XCTAssertEqual(Set(keys).count, keys.count, "all keys distinct afterwards")
        // A tied run at the very end re-keys toward an open end.
        let tail = items([("a", "a0"), ("b", "a1"), ("c", "a1")])
        XCTAssertEqual(apply(Ordering.place(["x"], at: .before("c"), in: tail), to: tail), ["a", "b", "x", "c"])
    }

    /// A key longer than 32 characters triggers a rebalance of the sequence, in the same order.
    func testRebalanceWhenKeysGrowTooLong() throws {
        var list = items([("a", "a0"), ("b", "a1")])
        var rebalances = 0
        for i in 0..<400 {
            let placed = Ordering.place(["n\(i)"], at: .after("a"), in: list)
            if placed.count > 1 { rebalances += 1 }
            XCTAssertTrue(placed.allSatisfy { $0.order.utf8.count <= Ordering.maxKeyLength })
            var byID = Dictionary(uniqueKeysWithValues: list.map { ($0.id, $0.order) })
            for p in placed { byID[p.id] = p.order }
            let before = list.map(\.id)
            list = byID.map { OrderedItem(id: $0.key, order: $0.value) }.sorted { orderPrecedes($0.order, $0.id, $1.order, $1.id) }
            var expected = before
            expected.insert("n\(i)", at: 1)
            XCTAssertEqual(list.map(\.id), expected)
        }
        // About one character per ~6 inserts at the same spot, so ~150 inserts per rebalance.
        XCTAssertGreaterThanOrEqual(rebalances, 1)
        XCTAssertLessThanOrEqual(rebalances, 4)
    }

    /// Keys that aren't valid fractional keys (another client, hand-edited data) fall back to a rebalance.
    func testInvalidNeighborKeysRebalance() {
        let list = items([("a", "0"), ("b", "zz")])
        let placed = Ordering.place(["x"], at: .after("a"), in: list)
        XCTAssertEqual(apply(placed, to: list), ["a", "x", "b"])
        XCTAssertTrue(placed.allSatisfy { FractionalIndex.isValidKey($0.order) })
    }

    /// Concurrent moves from two Macs, replayed in both orders: both converge, same item → later wins whole.
    func testConcurrentMovesConvergeInBothOrders() {
        var m = OpMaker()
        var base = AppState()
        base.apply(m.createList("L", name: "L", order: "a0"))
        for (i, id) in ["a", "b", "c", "d"].enumerated() {
            base.apply(m.createTask(id, list: "L", order: "a\(i)"))
        }
        let list = base.tasks.values.map { OrderedItem(id: $0.id, order: $0.order) }
            .sorted { orderPrecedes($0.order, $0.id, $1.order, $1.id) }
        // Mac 1 drags d to the top; Mac 2 drags a below c. Both computed against the same stale view.
        let p1 = Ordering.place(["d"], at: .top, in: list)
        let p2 = Ordering.place(["a"], at: .after("c"), in: list)
        let ops1 = p1.map { m.updateTask($0.id, Patch(list: "L", order: $0.order)) }
        let ops2 = p2.map { m.updateTask($0.id, Patch(list: "L", order: $0.order)) }
        var s1 = base, s2 = base
        for o in ops1 + ops2 { s1.apply(o) }
        for o in ops2 + ops1 { s2.apply(o) }
        func order(_ s: AppState) -> [String] {
            s.tasks.values.sorted { orderPrecedes($0.order, $0.id, $1.order, $1.id) }.map(\.id)
        }
        XCTAssertEqual(order(s1), ["d", "b", "c", "a"])
        XCTAssertEqual(order(s1), order(s2))
    }
}
